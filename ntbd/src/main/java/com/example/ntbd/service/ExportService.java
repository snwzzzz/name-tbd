package com.example.ntbd.service;

import com.example.ntbd.dto.PageDto;
import com.example.ntbd.dto.UiComponentDto;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

@Service
@RequiredArgsConstructor
public class
































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































ExportService {

    private final PageService pageService;
    private final UiComponentService uiComponentService;

    public String exportPageToHtml(Long pageId) {
        PageDto page = pageService.findById(pageId);
        List<UiComponentDto> components = uiComponentService.findByPageId(pageId);

        try {
            // Build tree
            Map<Long, List<UiComponentDto>> childrenMap = components.stream()
                    .filter(c -> c.parentId() != null)
                    .collect(Collectors.groupingBy(UiComponentDto::parentId));

            List<UiComponentDto> rootComponents = components.stream()
                    .filter(c -> c.parentId() == null)
                    .toList();

            // The root artboard in the Angular app is exactly 24x18
            int rootCols = 24;
            int rootRows = 18;

            StringBuilder htmlBuilder = new StringBuilder();
            for (UiComponentDto root : rootComponents) {
                htmlBuilder.append(renderComponent(root, childrenMap));
            }

            return "<!DOCTYPE html>\n" +
                    "<html lang=\"en\">\n" +
                    "<head>\n" +
                    "    <meta charset=\"UTF-8\">\n" +
                    "    <meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">\n" +
                    "    <title>Exported Page: " + page.name() + "</title>\n" +
                    "    <style>\n" +
                    "        body { margin: 0; padding: 0; font-family: sans-serif; background-color: #f5f5f5; overflow: hidden; }\n" +
                    "        .app-container {\n" +
                    "            display: grid;\n" +
                    "            width: 100vw;\n" +
                    "            height: 100vh;\n" +
                    "            grid-template-columns: repeat(" + rootCols + ", 1fr);\n" +
                    "            grid-template-rows: repeat(" + rootRows + ", 1fr);\n" +
                    "            /* No gap for root container to ensure perfect 100vh/100vw fitting if GridStack was flush, or you can add gap if needed */\n" +
                    "            box-sizing: border-box;\n" +
                    "        }\n" +
                    "        .widget-button { width: 100%; height: 100%; padding: 8px 16px; cursor: pointer; background: #007bff; color: white; border: none; border-radius: 4px; box-sizing: border-box; }\n" +
                    "        .widget-form { width: 100%; height: 100%; display: flex; flex-direction: column; gap: 10px; box-sizing: border-box; }\n" +
                    "        .widget-form input { padding: 8px; border: 1px solid #ccc; border-radius: 4px; box-sizing: border-box; }\n" +
                    "        .widget-text { width: 100%; height: 100%; display: flex; align-items: center; justify-content: center; background: white; border: 1px solid #ddd; border-radius: 4px; box-sizing: border-box; }\n" +
                    "        .widget-container { width: 100%; height: 100%; box-sizing: border-box; }\n" +
                    "    </style>\n" +
                    "</head>\n" +
                    "<body>\n" +
                    "    <div class=\"app-container\">\n" +
                    htmlBuilder.toString() +
                    "    </div>\n" +
                    "</body>\n" +
                    "</html>";

        } catch (Exception e) {
            throw new RuntimeException("Failed to export page", e);
        }
    }

    private String renderComponent(UiComponentDto c, Map<Long, List<UiComponentDto>> childrenMap) {
        int x = c.x() != null ? c.x().intValue() : 0;
        int y = c.y() != null ? c.y().intValue() : 0;
        int w = c.w() != null ? c.w().intValue() : 1;
        int h = c.h() != null ? c.h().intValue() : 1;

        // CSS Grid is 1-indexed
        int gridColumnStart = x + 1;
        int gridColumnEnd = gridColumnStart + w;
        int gridRowStart = y + 1;
        int gridRowEnd = gridRowStart + h;

        StringBuilder style = new StringBuilder();
        style.append("grid-column: ").append(gridColumnStart).append(" / ").append(gridColumnEnd).append("; ");
        style.append("grid-row: ").append(gridRowStart).append(" / ").append(gridRowEnd).append("; ");

        List<UiComponentDto> children = childrenMap.get(c.id());
        
        if (children != null && !children.isEmpty()) {
            // It's a container widget. 
            // The Angular app uses column: 'auto' and row: node.h for subgrids, meaning the nested grid
            // has exactly as many columns and rows as its width and height in the parent grid.
            int nestedCols = w;
            int nestedRows = h;
            
            style.append("display: grid; ");
            style.append("grid-template-columns: repeat(").append(nestedCols).append(", 1fr); ");
            style.append("grid-template-rows: repeat(").append(nestedRows).append(", 1fr); ");
            
            StringBuilder childrenHtml = new StringBuilder();
            for (UiComponentDto child : children) {
                childrenHtml.append(renderComponent(child, childrenMap));
            }
            
            return "<div class=\"widget-container\" style=\"" + style.toString() + "\">\n" + childrenHtml.toString() + "</div>\n";
        } else {
            // It's a leaf widget
            String type = c.type() != null ? c.type() : "default";
            Map<String, Object> props = c.props();
            
            String innerHtml = "";
            if ("button".equals(type)) {
                String label = (props != null && props.containsKey("label")) ? props.get("label").toString() : "Button";
                innerHtml = "<button class=\"widget-button\">" + label + "</button>";
            } else if ("form".equals(type) || "input".equals(type)) {
                String placeholder = (props != null && props.containsKey("placeholder")) ? props.get("placeholder").toString() : "Enter text...";
                innerHtml = "<div class=\"widget-form\"><input type=\"text\" placeholder=\"" + placeholder + "\" /></div>";
            } else {
                String text = (props != null && props.containsKey("text")) ? props.get("text").toString() : 
                              (props != null && props.containsKey("label") ? props.get("label").toString() : "Widget");
                innerHtml = "<div class=\"widget-text\">" + text + "</div>";
            }
            
            return "<div style=\"" + style.toString() + " padding: 4px; box-sizing: border-box;\">\n" + innerHtml + "</div>\n";
        }
    }
}
